import { readFileSync, writeFileSync } from 'node:fs';
import { zipSync, strToU8 } from 'fflate';
const materials = {
 IMPORT_GUIDE: ['../docs/markdown-format.md', 'import-guide.md'],
 IMPORT_TEMPLATE: ['../examples/template.md', 'template.md'],
 IMPORT_PROMPT: ['../docs/ai-prompt.md', 'ai-prompt.md'],
 IMPORT_EXAMPLE: ['../examples/code-and-math.md', 'examples/code-and-math.md'],
 IMPORT_CHOICE_EXAMPLE: ['../examples/choice.md', 'examples/choice.md'],
 IMPORT_KIT_README: ['../docs/import-kit-readme.md', 'README.md'],
};
let source = '// Generated by scripts/generate-import-guide.mjs. Edit the source Markdown files.\n';
const entries = {};
for (const [name, [path, entry]] of Object.entries(materials)) {
 const text = readFileSync(new URL(path, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
 source += 'export const ' + name + ' = ' + JSON.stringify(text) + ';\n';
 entries[entry] = strToU8(text);
}
writeFileSync(new URL('../src/domain/import-guide-content.ts', import.meta.url), source, 'utf8');
writeFileSync(new URL('../docs/recall-import-kit.zip', import.meta.url), zipSync(entries));
console.log('Import handbook and kit generated');
